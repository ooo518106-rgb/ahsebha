// Precompute expensive vector distances. Workers only inflate masks and blend the chosen shop colour.
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import { geometry } from '../src/wallet-geometry.js';
const masks = {};
function store(key, data, channels) {
  const raw = new Uint8Array(data.length / 5 * channels.length);
  for(let p=0; p<data.length/5; p++) for(let c=0;c<channels.length;c++) raw[p*channels.length+c]=data[p*5+channels[c]];
  masks[key]=deflateSync(raw,{level:9}).toString('base64');
}
for (const f of [{W:375,H:144},{W:344,H:112}]) {
  for (let n=1; n<=12; n++) store(`${f.W}:ring:${n}`, geometry(f,n,false,'cup').data,[0,1]);
  for (const ready of [false,true]) store(`${f.W}:centre:${+ready}`, geometry(f,10,ready,'cup').data,[2]);
  store(`${f.W}:decor`,geometry(f,10,false,'cup').data,[3]);
  for(const icon of ['cupcake','scissors','dish','bag','star']) store(`${f.W}:icon:${icon}`,geometry(f,10,false,icon).data,[4]);
}
const out=`// Generated by scripts/build-wallet-masks.mjs. Do not hand-edit.\nimport { CUP_WIDTH, CUP_HEIGHT } from './reward-art.js';\nconst MASKS=${JSON.stringify(masks)};\nconst cache=new Map();
async function mask(key) {
  if (!cache.has(key)) {
    if(cache.size>=16) cache.delete(cache.keys().next().value);
    const promise=(async()=>{
      const bytes=Uint8Array.from(atob(MASKS[key]),c=>c.charCodeAt(0));
      return new Uint8Array(await new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate'))).arrayBuffer());
    })();
    cache.set(key,promise);
    promise.catch(()=>{if(cache.get(key)===promise)cache.delete(key);});
  }
  return cache.get(key);
}
export async function walletGeometry(f,slots,ready,icon) {
  const [ring,centre,decor,art]=await Promise.all([mask(f.W+':ring:'+slots),mask(f.W+':centre:'+Number(ready)),mask(f.W+':decor'),icon==='cup'?null:mask(f.W+':icon:'+icon)]);
  const artH=f.H*0.78,artW=artH*CUP_WIDTH/CUP_HEIGHT;
  return {ring,centre,decor,art,artW,artH,artX:f.W*0.745-artW/2,artY:f.H*0.55-artH/2};
}\n`;
writeFileSync(new URL('../src/wallet-masks.js',import.meta.url),out);
console.log('Generated wallet-masks.js:',out.length,'bytes');
