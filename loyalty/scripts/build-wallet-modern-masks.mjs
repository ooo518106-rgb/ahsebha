import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import { geometry } from '../src/wallet-modern-geometry.js';
const masks = {};
for(const f of [{W:375,H:144},{W:344,H:112}]) masks[f.W]=deflateSync(geometry(f),{level:9}).toString('base64');
writeFileSync(new URL('../src/wallet-modern-masks.js',import.meta.url),`// Generated by scripts/build-wallet-modern-masks.mjs.\nconst MASKS=${JSON.stringify(masks)};
const cache=new Map();
export async function modernGeometry(width) {
  if(!cache.has(width)) {
    const p=(async()=>{
      const bytes=Uint8Array.from(atob(MASKS[width]),c=>c.charCodeAt(0));
      return new Uint8Array(await new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate'))).arrayBuffer());
    })();
    cache.set(width,p);
    p.catch(()=>{if(cache.get(width)===p)cache.delete(width);});
  }
  return cache.get(width);
}
`);
console.log('Generated wallet-modern-masks.js');
